        private static bool BuildObstacle(string name, string fbxPath, bool jumpable,
                                          Material palette = null, float scale = 1f, bool upright = false)
        {
            string path = $"{Root}/Obstacles/{name}.prefab";
            if (Exists(path)) return false;

            GameObject root = NewRoot(name);
            GameObject mesh = AttachMesh(root, fbxPath, scale, upright);
            if (mesh == null) { Object.DestroyImmediate(root); return false; }

            if (palette != null) MaterialLibrary.AssignPalette(mesh, palette, MaterialLibrary.RoadLine());

            SafeSetTag(root, Tags.Obstacle);

            var collider = root.AddComponent<BoxCollider>();
            collider.isTrigger = true;
            // Fit the trigger to what is actually drawn. A hardcoded box is how you get
            // an obstacle you crash into before you reach it, or one you drive through:
            // these meshes differ hugely in size (a cone is under a metre, a traffic
            // light over four) and the prefab scale differs per pack.
            FitTriggerToMesh(collider, mesh,
                fallback: jumpable ? new Vector3(1.3f, 0.9f, 1.3f) : new Vector3(1.4f, 3.2f, 1.4f));

            var obstacle = root.AddComponent<Obstacles.Obstacle>();
            obstacle.clearableByJump = jumpable;

            MakeMovingTrigger(root);

            return Save(root, path);
        }

        /// <summary>
        /// Width of a road tile, in world units, after <see cref="RoadTileScale"/>.
        /// Three lanes at <c>LaneModel.LaneWidth</c> (3.0) plus a margin each side so the
        /// outer lanes are not flush with the kerb.
        ///
        /// The tile is square, so this is also its length along Z — which is what
        /// <c>RoadScroller.tileLength</c> must be set to.
        /// </summary>
        public const float RoadTileWidth = 12f;

        /// <summary>
        /// Scale that brings a rotated road tile to <see cref="RoadTileWidth"/> on Z.
        ///
        /// Measured inside Unity, not inferred from the file: with the importer set to
        /// <c>globalScale = 100</c> the tile delivers as <b>200 x 200 x 25</b>, and after
        /// <see cref="QuaterniusUprightRotation"/> it is <b>200 x 25 x 200</b> — 200 wide,
        /// 25 thick, 200 long. 12/200 = 0.06 gives a 12 x 1.5 x 12 tile.
        /// </summary>
        public const float RoadTileSourceSize = 200f;
        public const float RoadTileScale = RoadTileWidth / RoadTileSourceSize;

        // ------------------------------------------------------------------
        // Quaternius orientation and scale — every number here was MEASURED in the
        // editor via Renderer.bounds, never derived from the FBX file's bytes.
        //
        // Two properties of these packs drive everything:
        //
        //  1. UNITS. The mesh data is authored tiny (Street_Straight's Mesh.bounds is
        //     0.02 x 0.02 x 0.0025) and `useFileScale` honours it, so at the default
        //     import settings every prop arrives at ~1/100th of usable size. The
        //     importers are set to `globalScale = 100, useFileScale = false` — see
        //     ModelAxisFixer. The props/streets/RPG packs need this; the character
        //     packs do NOT (they are already metre-scale) and are exempted there.
        //
        //  2. ORIENTATION. Props are authored Z-up, so their tallest extent lands on Z
        //     and they lie on their side unless rotated -90 on X. Measured as-is:
        //
        //       Street_Straight  200.00 x 200.00 x  25.00   -> -90X -> 200 x 25 x 200
        //       Coin              73.67 x  18.12 x  73.77   -> -90X ->  74 x 74 x 18
        //       Sign_Stop          2.33 x  13.84 x  53.77   -> -90X
        //       TrafficLight      12.30 x   8.96 x  87.09   -> -90X
        //       Streetlight      13.17 x  13.17 x 109.04    -> -90X
        //       Tree1            206.73 x 298.78 x 409.91   -> -90X
        //       Bush1            107.42 x 107.41 x 149.12   -> -90X
        //       Male_Casual        1.96 x   4.93 x   1.13   -> already upright, no rot
        //
        // Scale = target size / measured size on the axis that defines the object:
        //
        //   prefab        measured after -90X        target        scale
        //   Coin           73.67 wide                1.3 wide     0.01765
        //   PowerUp        73.67 wide                1.7 wide     0.02308
        //   StopSign       53.77 tall                2.6 tall     0.04835
        //   TrafficLight   87.09 tall                4.2 tall     0.04823
        //   Streetlight   109.04 tall                6.5 tall     0.05961
        //   Tree          409.91 tall                6.5 tall     0.01586
        //   Bush          149.12 tall                1.5 tall     0.01006
        //   Pedestrian      4.93 tall (no rot)       1.8 tall     0.36518
        // ------------------------------------------------------------------

        /// <summary>
        /// Stands a Z-up Quaternius prop upright. Applied to the mesh child, never to the
        /// prefab root — the root owns the collider, and rotating it would tip the hitbox
        /// out of alignment with the lanes.
        /// </summary>
        private static readonly Quaternion QuaterniusUprightRotation = Quaternion.Euler(-90f, 0f, 0f);

        /// <summary>
        /// The road tile needs the upright rotation <i>and</i> a quarter turn on Y.
        ///
        /// The street mesh is authored running along X. After only the -90 X correction
        /// its lane-marking submesh measures 200 x 2 x 6 in world space — 200 units long
        /// across the player's path — so the dashes run sideways like a zebra crossing.
        /// Adding 90 on Y turns that to 6 x 2 x 200, i.e. along the direction of travel,
        /// which is what makes it read as a road instead of a paved square.
        /// </summary>
        private static readonly Quaternion RoadTileRotation = Quaternion.Euler(-90f, 90f, 0f);

        // Coin diameter 0.9 against a 1.5-wide car: big enough to read at speed, small
        // enough that three abreast in a lane still look like collectables rather than
        // roadblocks. Measured source is 73.67 wide, so 0.9/73.67.
        private const float CoinScale = 0.01222f;
        private const float StopSignScale = 0.04835f;
        private const float TrafficLightScale = 0.04823f;
        private const float StreetlightScale = 0.05961f;
        private const float TreeScale = 0.01586f;
        private const float BushScale = 0.01006f;

        // Power-up scales — RETIRED. The Quaternius RPG power-up meshes (heart,
        // star, armor, arrow, snowflake, potion) were replaced by procedurally-
        // authored icons in PowerUpMeshBuilder. Each procedural icon is authored
        // at exactly 1 unit tall with its lowest vertex at y = 0, so no
        // per-FBX import-scale constant is needed. The Coin prefab still uses
        // Quaternius/RPG/Coin.fbx (see CoinScale, defined next to BuildCoin).

        /// <summary>
        /// Builds the road tile from scratch instead of using the Quaternius street mesh.
        ///
        /// The pack mesh was measured and rejected: it is a coarse quad strip with
        /// vertices only at x = -6, -2, 0, +2, +6, and its centre band sits 0.18 units
        /// LOWER than the rest. On a 3-lane road that dip runs straight down the middle
        /// lane, so the centre lane visibly sinks and the outer lanes read as raised
        /// kerbs — which is exactly how it looked. It also carries no markings at the
        /// lane boundaries, only one stripe down its centre.
        ///
        /// A road tile is a flat rectangle. Generating it gives a guaranteed-planar
        /// surface at y = 0, dashes exactly on the lane boundaries, pavements at a
        /// deliberate height, and it costs 6 quads instead of a 200-unit imported mesh.
        /// The "everything from packs" rule is about *art*; a flat quad is geometry, and
        /// the pack mesh actively cannot express a correct 3-lane road.
        /// </summary>
        private static bool BuildRoadTile(string name, string fbxPath)
        {
            string path = $"{Root}/Road/{name}.prefab";
            if (Exists(path)) return false;

            GameObject root = NewRoot(name);

            float half = RoadTileWidth * 0.5f;          // 6
            float driveHalf = Gameplay.LaneModel.LaneWidth * 1.5f;   // 4.5 — outer lane edge

            // Driving surface: one flat quad at exactly y = 0, spanning the full tile.
            MakeQuad(root, "Asphalt", new Vector3(0f, 0f, 0f),
                     new Vector2(driveHalf * 2f, RoadTileWidth), MaterialLibrary.Asphalt());

            // Pavements either side, raised so they read as kerbs the car cannot drive on.
            float pavementWidth = half - driveHalf;      // 1.5
            float pavementCentre = driveHalf + pavementWidth * 0.5f;
            MakeKerb(root, "Pavement_L", -pavementCentre, pavementWidth);
            MakeKerb(root, "Pavement_R", +pavementCentre, pavementWidth);

            // Grass verges running out to the building line.
            //
            // Without these the world simply stops at x = +-6 and every building beyond
            // it hangs over the skybox — which is what "the buildings float" actually
            // was. It is not a Y offset: there is no ground under them at all. The verge
            // has to reach past the furthest building (sideOffset + jitter) or the seam
            // is just pushed further out instead of being closed.
            float vergeInner = half;
            float vergeOuter = GroundHalfWidth;
            float vergeWidth = vergeOuter - vergeInner;
            float vergeCentre = vergeInner + vergeWidth * 0.5f;
            MakeQuad(root, "Grass_L", new Vector3(-vergeCentre, PavementHeight, 0f),
                     new Vector2(vergeWidth, RoadTileWidth), MaterialLibrary.Grass());
            MakeQuad(root, "Grass_R", new Vector3(+vergeCentre, PavementHeight, 0f),
                     new Vector2(vergeWidth, RoadTileWidth), MaterialLibrary.Grass());

            BuildLaneMarkings(root);

            // Road is scenery; no collider. The player is held on a fixed Y.
            return Save(root, path);
        }

        /// <summary>Height of the pavement above the road surface.</summary>
        public const float PavementHeight = 0.18f;

        /// <summary>
        /// Half-width of the whole ground plate, road + pavement + grass verge.
        ///
        /// Must exceed the furthest scenery placement (`ScenerySpawner.sideOffset` +
        /// `sideOffsetJitter`, currently 13) AND the furthest back-row placement
        /// (`backRowOffset + backRowOffsetJitter`, currently 22 + 5 = 27) or buildings
        /// spawn past the edge of the world and hang over the skybox. 32 leaves headroom
        /// for both rows so the horizon reads as continuous ground rather than a strip the
        /// camera can see the end of.
        /// </summary>
        public const float GroundHalfWidth = 32f;

        /// <summary>
        /// A raised pavement slab: a top face at <see cref="PavementHeight"/> plus a
        /// vertical face along its inner edge, so the kerb has visible thickness from the
        /// player's low camera rather than looking like a painted stripe.
        /// </summary>
        private static void MakeKerb(GameObject root, string name, float centreX, float width)
        {
            MakeQuad(root, name, new Vector3(centreX, PavementHeight, 0f),
                     new Vector2(width, RoadTileWidth), MaterialLibrary.Pavement());

            // Inner vertical face, turned to face the road.
            float innerX = centreX > 0f ? centreX - width * 0.5f : centreX + width * 0.5f;
            var face = new GameObject(name + "_Face", typeof(MeshFilter), typeof(MeshRenderer));
            face.transform.SetParent(root.transform, false);
            face.transform.localPosition = new Vector3(innerX, PavementHeight * 0.5f, 0f);
            face.transform.localRotation = Quaternion.Euler(0f, 0f, centreX > 0f ? 90f : -90f);

            var mesh = QuadMesh(name + "_Face", new Vector2(PavementHeight, RoadTileWidth));
            face.GetComponent<MeshFilter>().sharedMesh = mesh;
            face.GetComponent<MeshRenderer>().sharedMaterial = MaterialLibrary.Pavement();
        }

        /// <summary>A flat, upward-facing quad parented to <paramref name="root"/>.</summary>
        private static void MakeQuad(GameObject root, string name, Vector3 localPosition, Vector2 size, Material material)
        {
            var go = new GameObject(name, typeof(MeshFilter), typeof(MeshRenderer));
            go.transform.SetParent(root.transform, false);
            go.transform.localPosition = localPosition;

            go.GetComponent<MeshFilter>().sharedMesh = QuadMesh(name, size);
            go.GetComponent<MeshRenderer>().sharedMaterial = material;
        }

        /// <summary>An XZ-plane quad of the given size, centred on its origin, facing +Y.</summary>
        private static Mesh QuadMesh(string name, Vector2 size)
        {
            float hx = size.x * 0.5f, hz = size.y * 0.5f;
            var mesh = new Mesh
            {
                name = name,
                vertices = new[]
                {
                    new Vector3(-hx, 0f, -hz), new Vector3(-hx, 0f, hz),
                    new Vector3(hx, 0f, hz),   new Vector3(hx, 0f, -hz),
                },
                triangles = new[] { 0, 1, 2, 0, 2, 3 },
                normals = new[] { Vector3.up, Vector3.up, Vector3.up, Vector3.up },
                uv = new[] { Vector2.zero, Vector2.up, Vector2.one, Vector2.right },
            };
            mesh.RecalculateBounds();
            return mesh;
        }


        private static bool BuildCoin()
        {
            string path = $"{Root}/Coin.prefab";
            if (Exists(path)) return false;

            GameObject root = NewRoot("Coin");
            GameObject mesh = AttachMesh(root, $"{Quaternius}/RPG/Coin.fbx", scale: CoinScale, upright: true);
            if (mesh == null) { Object.DestroyImmediate(root); return false; }

            // Single "Gold" material slot on this mesh; the spawner overwrites it per type.
            MaterialLibrary.AssignPalette(mesh, MaterialLibrary.GetOrCreate(
                $"{MaterialLibrary.CoinsFolder}/CoinRed.mat", new Color(0.918f, 0.263f, 0.208f)));

            // No rotation. The FBX's own node transform already stands the disc upright
            // (73.7 x 73.8 wide, 18.1 thick once imported), so it faces the player as-is.
            // The previous 90-degree X rotation here tipped it flat, which is why coins
            // rendered as white plates lying on the road.

            var collider = root.AddComponent<BoxCollider>();
            collider.isTrigger = true;
            // Deliberately generous, and deliberately NOT fitted to the mesh: a coin is a
            // reward, so its pickup volume should be forgiving. Cubic so it catches the
            // player at any approach angle.
            collider.size = new Vector3(1.9f, 1.9f, 1.9f);

            var pickup = root.AddComponent<Coins.CoinPickup>();
            pickup.coinMeshRenderer = mesh.GetComponentInChildren<MeshRenderer>(true);

            MakeMovingTrigger(root);

            return Save(root, path);
        }

        /// <summary>
        /// One imported-pack mesh per power-up type. Replaces the earlier
        /// procedurally-authored icons (see <c>PowerUpMeshBuilder</c>, now
        /// orphaned on disk) with real silhouettes sourced from Kenney and
        /// Quaternius packs so the mesh reads as the gameplay effect it
        /// performs — a Subway-Surfers-style crane magnet for CoinMagnet,
        /// a star for TwoX, a warrior shield for Shield, a propane cylinder
        /// for Nitro, a 6-arm snowflake for PoliceFreeze.
        ///
        /// Sourcing (2026-08-17):
        ///   Magnet      Kenney Factory Kit        FactoryKit/crane-magnet.fbx
        ///   TwoX        Kenney Platformer Kit     PlatformerKit/star.fbx
        ///   Shield      Kenney Mini Dungeon       MiniDungeon/shield-round.fbx
        ///   Nitro       Quaternius Survival       Survival/PropaneTank.blend
        ///   Freeze      Kenney Holiday Kit        HolidayKit/snowflake-a.fbx
        ///
        /// Two of the icons (Magnet, Shield) ship multiple material slots;
        /// the imported FBXs render with whatever materials the pack bundles.
        /// This builder overrides those per-renderer with the icon's tint +
        /// secondary materials so every power-up reads at game-speed as the
        /// identity colour the player has been trained to expect (magnet =
        /// gold body + red poles, etc.). Single-slot icons (TwoX, Nitro,
        /// Freeze) override the lone renderer with the tint.
        ///
        /// <see cref="ImportScale"/> is per-entry because the packs author at
        /// wildly different scales. Kenney FBXs carry no node transform and
        /// import 1:1 (see CLAUDE.md §3a), so a Kenney icon's authored height
        /// arrives in world units directly — the values below normalise each
        /// picked mesh to <b>1 world unit tall</b> (verified by measuring
        /// Renderer.bounds in Unity MCP, 2026-08-17): 1 / bounds.size.y.
        ///
        /// <see cref="Upright"/> is true only for Z-up Quaternius sources
        /// (the Survival <c>.blend</c> files, which the existing
        /// <see cref="GDGGo.EditorTools.ModelAxisFixer"/> engine treats as
        /// Quaternius props requiring the <c>-90 X</c> "stand it up" rotation).
        /// Kenney FBXs are already Y-up — passing upright=true would tip
        /// them onto their sides.
        /// </summary>
        private static readonly (PowerUps.PowerUpType Type, string Name, Color Hue,
                                 bool HasSecondary, string FbxPath,
                                 float ImportScale, bool Upright)[] PowerUpVariants =
        {
            (PowerUps.PowerUpType.CoinMagnet,    "Magnet",  new Color(0.98f, 0.74f, 0.02f), true,
                                             $"{Kenney}/FactoryKit/crane-magnet.fbx", 1.11f, false),
            (PowerUps.PowerUpType.TwoX,         "TwoX",    new Color(0.20f, 0.85f, 0.35f), false,
                                             $"{Kenney}/PlatformerKit/star.fbx", 2.75f, false),
            (PowerUps.PowerUpType.Shield,       "Shield",  new Color(0.26f, 0.52f, 0.96f), true,
                                             $"{Kenney}/MiniDungeon/shield-round.fbx", 2.63f, false),
            (PowerUps.PowerUpType.Nitro,        "Nitro",   new Color(0.20f, 0.90f, 1.00f), false,
                                             $"{Quaternius}/Survival/PropaneTank.blend", 0.0069f, true),
            (PowerUps.PowerUpType.PoliceFreeze, "Freeze",  new Color(0.85f, 0.35f, 0.95f), false,
                                             $"{Kenney}/HolidayKit/snowflake-a.fbx", 2.50f, false),
        };

        /// <summary>
        /// Builds one prefab per power-up type, each loading its own imported
        /// mesh from a Kenney or Quaternius pack (see <see cref="PowerUpVariants"/>).
        /// The silhouette — not just the colour — tells the player what they are
        /// grabbing: a crane magnet for CoinMagnet, a star for TwoX, a warrior
        /// shield for Shield, a propane cylinder for Nitro, a snowflake for PoliceFreeze.
        ///
        /// Each imported mesh arrives with whatever material slots the pack
        /// bundled; we override the per-renderer shared materials with our
        /// tint + secondary (for two-slot icons) so every pickup reads at
        /// game-speed as the identity colour the player has been trained to
        /// expect — magnet gold + red poles, shield blue + silver stripe, etc.
        ///
        /// Each prefab carries the same collider + components the old one did —
        /// only the mesh differs — so <see cref="PowerUps.PowerUpEffect"/> and
        /// <see cref="PowerUps.PowerUpSpawner"/> plug in unchanged. Idempotent:
        /// existing prefabs are left alone, so this stays safe under "Run Full
        /// Project Setup" re-runs.
        /// </summary>
        private static int BuildPowerUps(ref int built)
        {
            foreach (var (type, name, hue, hasSecondary, fbxPath, importScale, upright) in PowerUpVariants)
            {
                string path = $"{Root}/PowerUps/PowerUp_{name}.prefab";
                if (Exists(path)) { continue; }

                GameObject rootObj = NewRoot($"PowerUp_{name}");

                // Imported silhouette from a real pack mesh. Kenney FBXs ship
                // Y-up 1:1 (no node transform); Quaternius .blend files are
                // Z-up centimetre-scale and the existing ModelAxisFixer ×100
                // pre-scale brings them to metre world units at import.
                // Per-entry ImportScale then normalises each picked mesh to
                // exactly 1 world unit tall (verified via Renderer.bounds).
                // Upright applies the -90 X rotation only for Z-up Quaternius
                // sources — Kenney is already Y-up, so passing it would tip
                // those meshes onto their sides.
                GameObject meshGo = AttachMesh(rootObj, fbxPath, importScale, upright);
                if (meshGo == null)
                {
                    Object.DestroyImmediate(rootObj);
                    Debug.LogWarning($"[PrefabsBuilder] AttachMesh returned null for {name} ({fbxPath}) — PowerUp_{name} not built.");
                    continue;
                }

                // Primary tint material — the icon body. Pumped emission (×2.2)
                // reads as self-lit even in shadow under Built-in (no Bloom).
                // Combined with the halo below, a power-up now reads as *glowing*
                // rather than just bright-tinted.
                Material tintMat = MaterialLibrary.GetOrCreate(
                    $"{MaterialLibrary.WorldFolder}/PowerUp_{name}.mat", hue, 0.85f, 0.4f);
                MaterialLibrary.SetEmission(tintMat, hue * 2.2f);

                // Secondary material — used by the two-material icons (magnet red
                // poles, shield silver stripe). Single-material icons (star,
                // cylinder, snowflake) skip the secondary assignment.
                Material secondaryMat = null;
                if (hasSecondary)
                {
                    secondaryMat = SecondaryPowerUpMaterial(type, name, hue);
                }

                // Override the imported pack-bundled materials with our tint +
                // secondary. The proc-gen builder used "_A"/"_B" child-naming to
                // distinguish slots; imported FBXs don't follow that convention,
                // so for two-slot icons we treat the first renderer found as the
                // primary body and the second as the secondary detail. A single
                // renderer always gets the tint. Order is the natural
                // GetComponentsInChildren order, which matches the FBX's child
                // export order — the same order the pack's own colours use.
                var renderers = meshGo.GetComponentsInChildren<MeshRenderer>(true);
                for (int i = 0; i < renderers.Length; i++)
                {
                    if (hasSecondary && i > 0)
                        renderers[i].sharedMaterial = secondaryMat;
                    else
                        renderers[i].sharedMaterial = tintMat;
                }

                // Additive glow halo — a two-layer billboarded radial glow (bright
                // core + soft halo) sibling of the mesh, so it tracks the camera
                // while the silhouette spins on Y. The Subway-Surfers read: a true
                // soft glow halo around the floating object, not a flat disc.
                AddGlowHalo(rootObj, name, hue, meshGo);

                var collider = rootObj.AddComponent<BoxCollider>();
                collider.isTrigger = true;
                collider.size = new Vector3(2f, 2f, 2f);

                var effect = rootObj.AddComponent<PowerUps.PowerUpEffect>();
                effect.type = type;
                // tintTarget points at the FIRST renderer found — Configure() will tint
                // all of them via the shared material anyway, and we set the tint above
                // so an absent tintTarget is a null-op, not a loss of colour.
                effect.tintTarget = meshGo.GetComponentInChildren<MeshRenderer>(true);

                rootObj.AddComponent<PowerUps.RotateSlow>();

                MakeMovingTrigger(rootObj);

                if (Save(rootObj, path)) built++;
            }
            return built;
        }

        /// <summary>
        /// Builds (or returns an existing) the *secondary* material for two-part
        /// icons — the painted detail on top of the icon body. Different per
        /// power-up so the silhouette has a clear two-colour read:
        ///   Magnet poles — pure Google Red #EA4335 (universal N/S pole marker)
        ///   Shield stripe — near-white (universal heraldic crest colour)
        ///   (Fuel handled by BuildFuelPrefab with its own darker-orange cap mat.)
        /// The secondary is intentionally NOT emissive — it reads as a painted
        /// detail on the icon, not a second light source.
        /// </summary>
        private static Material SecondaryPowerUpMaterial(PowerUps.PowerUpType type, string name, Color hue)
        {
            switch (type)
            {
                case PowerUps.PowerUpType.CoinMagnet:
                    // Magnet poles — pure Google Red.
                    return MaterialLibrary.GetOrCreate(
                        $"{MaterialLibrary.WorldFolder}/PowerUp_{name}_Pole.mat",
                        new Color(0.918f, 0.200f, 0.208f), 0.6f, 0.05f);

                case PowerUps.PowerUpType.Shield:
                    // Shield crest stripe — near-white with low specular so it
                    // doesn't read as a mirror under the directional light.
                    return MaterialLibrary.GetOrCreate(
                        $"{MaterialLibrary.WorldFolder}/PowerUp_{name}_Stripe.mat",
                        new Color(0.92f, 0.92f, 0.92f), 0.4f, 0.0f);

                default:
                    // Two-material path is only used by Magnet and Shield; fall
                    // back to the primary hue so any future added pair stays
                    // single-hued.
                    return MaterialLibrary.GetOrCreate(
                        $"{MaterialLibrary.WorldFolder}/PowerUp_{name}_Secondary.mat",
                        hue, 0.6f, 0.0f);
            }
        }

        /// <summary>
        /// Builds the fuel pickup prefab from the Quaternius Survival pack's
        /// <c>GasCan.blend</c> — a real jerry-can silhouette sourced from an
        /// imported pack. Fuel previously reused the Coin mesh + an orange
        /// material; a canister reads as "a canister" rather than "another
        /// coin", which is the exact problem CLAUDE.md §Fuel warns about: a
        /// fuel can that reads as another coin defeats the mechanic.
        ///
        /// The imported <c>GasCan</c> mesh ships with Quaternius Survival's
        /// own materials; we override the per-renderer shared materials with
        /// our hot-orange body and a darker orange cap so the can reads as a
        /// two-tone glowing pickup regardless of the bundled pack texture.
        ///
        /// The CoinPickup + CoinSpawner integration uses <see cref="CoinType.Fuel"/>
        /// for the score/fuel short-circuit; we set that on the prefab so a pickup
        /// of any fuel instance routes correctly without the spawner having to
        /// tag it.
        /// </summary>
        public static bool BuildFuelPrefab()
        {
            string path = $"{Root}/PowerUps/Fuel.prefab";
            if (Exists(path)) return false;

            GameObject rootObj = NewRoot("Fuel");

            // Quaternius Survival's GasCan.blend is a real jerry-can silhouette.
            // ModelAxisFixer pre-applies ×100 import scale (Survival is under
            // Assets/Models/Quaternius/, so it's treated as a Quaternius prop),
            // bringing the can to ~124 world units tall post-×100. Per-entry
            // scale of 1/124 = 0.0080f normalises the can to ~1 world unit
            // tall (verified via Renderer.bounds in Unity MCP). Upright pass
            // applies the -90 X rotation that stands the Z-up blend file up
            // on Y, then re-seats the base onto y = 0 so the can floats
            // cleanly above the glow halo instead of half-burying inside it.
            GameObject meshGo = AttachMesh(
                rootObj, $"{Quaternius}/Survival/GasCan.blend", scale: 0.0080f, upright: true);
            if (meshGo == null)
            {
                Object.DestroyImmediate(rootObj);
                Debug.LogWarning("[PrefabsBuilder] AttachMesh returned null for GasCan.blend — Fuel prefab not built.");
                return false;
            }

            // Fuel is deliberately outside the Google Palette: hot orange
            // (#FF6B0D) so it doesn't read as "another coin".
            Color fuelOrange = new Color(1.0f, 0.42f, 0.05f);
            Material liquidMat = MaterialLibrary.GetOrCreate(
                $"{MaterialLibrary.WorldFolder}/Fuel.mat", fuelOrange, 0.55f, 0.0f);
            // Pumped emission (×1.6 was ×0.9) — same reasoning as BuildPowerUps:
            // under Built-in without Bloom, emission just brightens the lit
            // surface, so the halo plus a stronger emission is what makes a fuel
            // can read as glowing.
            MaterialLibrary.SetEmission(liquidMat, fuelOrange * 1.6f);

            // Darker orange for the cap + handle so the can reads as a two-tone
            // object — the silhouette stays unambiguous from any angle.
            Material capMat = MaterialLibrary.GetOrCreate(
                $"{MaterialLibrary.WorldFolder}/Fuel_Cap.mat",
                new Color(0.68f, 0.28f, 0.04f), 0.6f, 0.0f);

            // Override the imported GasCan's bundled materials with our hot-orange
            // body + dark orange cap. The proc-gen builder used "_A"/"_B" child
            // naming to distinguish slots; the imported blend file doesn't follow
            // that convention, so the first MeshRenderer carries the body and
            // every subsequent renderer carries the cap. A single-renderer can
            // stays single-material (the whole can reads as hot orange).
            var renderers = meshGo.GetComponentsInChildren<MeshRenderer>(true);
            for (int i = 0; i < renderers.Length; i++)
            {
                renderers[i].sharedMaterial = (i > 0) ? capMat : liquidMat;
            }

            AddGlowHalo(rootObj, "Fuel", fuelOrange, meshGo);

            var collider = rootObj.AddComponent<BoxCollider>();
            collider.isTrigger = true;
            // Generous pickup volume — a fuel can is a milestone, not a tight grab.
            collider.size = new Vector3(1.6f, 1.8f, 1.6f);

            var pickup = rootObj.AddComponent<Coins.CoinPickup>();
            // Pre-tag the prefab instance so an unconfigured spawner still routes a
            // fuel pickup as fuel — the field is normally written by CoinSpawner at
            // spawn time, but pre-tagging is a safety belt and is cheap.
            pickup.coinType = Coins.CoinType.Fuel;
            pickup.coinValue = 0;
            pickup.coinMeshRenderer = meshGo.GetComponentInChildren<MeshRenderer>(true);

            MakeMovingTrigger(rootObj);

            return Save(rootObj, path);
        }

        /// <summary>
        /// Builds the Subway-Surfers-style two-layer glow halo for a floating power-up:
        ///
        ///   Glow (root sibling of "Mesh" — never rotates with the silhouette spin)
        ///   ├─ BrightCore   — 1.3× mesh bounds, bright tint. The "energy spike" centre.
        ///   └─ SoftHalo     — 2.8× mesh bounds, faint tint. The wide diffuse aura.
        ///
        /// Both layers are billboarded quads textured with a radial-gradient PNG
        /// (white core fading to transparent at the quad edge), blended
        /// additively. The billboard component guarantees the glow always
        /// presents a full circle to the camera regardless of viewing angle, and
        /// the radial sprite gives a smooth soft falloff that reads as a true
        /// volumetric glow rather than a flat plate.
        ///
        /// Why two layers: Subway Surfers power-ups read as the object floating
        /// inside a **glowing fog**. One layer with a single tint either washes
        /// the centre out white (too bright) or fails to bleed past the
        /// silhouette (too dim). The tight bright core plus wide faint halo is
        /// the only configuration that reads under both peripheral vision and
        /// direct gaze.
        ///
        /// The glow rig is parented DIRECTLY to the pickup root rather than to
        /// the "Mesh" child. The mesh's <see cref="RotateSlow"/> spins it on Y,
        /// and letting the halo ride along would smear the billboarded sprite
        /// into a spinning plate — the exact horizontal-disc look players
        /// reject. A direct-root sibling means the billboard live-tracks the
        /// camera independently, so the halo stays a steady sphere around the
        /// spinning silhouette.
        /// </summary>
        private static void AddGlowHalo(GameObject root, string name, Color hue, GameObject mesh)
        {
            // Measure the mesh's bounds so the halo size scales per pickup — a magnet
            // and an arrow have different silhouettes, so the glow ring around them
            // should too.
            float meshSize = 1f;
            if (mesh != null)
            {
                var renderers = mesh.GetComponentsInChildren<Renderer>(true);
                if (renderers.Length > 0)
                {
                    Bounds b = renderers[0].bounds;
                    for (int i = 1; i < renderers.Length; i++) b.Encapsulate(renderers[i].bounds);
                    meshSize = Mathf.Max(b.size.x, b.size.y, b.size.z);
                    if (meshSize < 0.8f) meshSize = 0.8f;
                }
            }

            // Outer rig holding both halo sprites. Parented to root (NOT to the
            // spinning mesh child) so the billboards track the camera independently.
            var rig = new GameObject("GlowHalo");
            rig.transform.SetParent(root.transform, false);
            rig.transform.localPosition = Vector3.zero;
            rig.transform.localRotation = Quaternion.identity;
            rig.transform.localScale = Vector3.one;

            // Shared radial texture asset. Created at first build, reused after.
            const string glowTexPath = "Assets/Textures/Glow/GlowRadial.png";

            // Bright core — 1.3× mesh bounds, near full-intensity tint.
            Color brightTint = new Color(hue.r * 2.5f, hue.g * 2.5f, hue.b * 2.5f, 1.0f);
            Material brightMat = MaterialLibrary.GetOrCreateTexturedGlow(
                $"{MaterialLibrary.WorldFolder}/PowerUp_{name}_GlowCore.mat",
                glowTexPath, brightTint);
            BuildGlowSprite(rig.transform, "BrightCore", meshSize * 1.3f, brightMat);

            // Soft halo — 2.8× mesh bounds, fainter tint.
            Color haloTint = new Color(hue.r * 1.4f, hue.g * 1.4f, hue.b * 1.4f, 0.55f);
            Material haloMat = MaterialLibrary.GetOrCreateTexturedGlow(
                $"{MaterialLibrary.WorldFolder}/PowerUp_{name}_GlowHalo.mat",
                glowTexPath, haloTint);
            // Render the soft halo first so the bright core overlays it.
            GameObject haloSprite = BuildGlowSprite(rig.transform, "SoftHalo", meshSize * 2.8f, haloMat);
            haloSprite.transform.SetAsFirstSibling();
        }

        /// <summary>
        /// Builds one billboarded quad child of <paramref name="parent"/>: a 1×1
        /// quad centred on the origin, facing +Z, scaled by <paramref name="size"/>
        /// on X and Y. A <see cref="PowerUps.Billboard"/> component makes the quad
        /// live-track the main camera each frame so the radial quad always
        /// presents a circle to the player.
        /// </summary>
        private static GameObject BuildGlowSprite(Transform parent, string spriteName, float size, Material mat)
        {
            var go = new GameObject(spriteName);
            go.transform.SetParent(parent, false);
            go.transform.localPosition = Vector3.zero;
            go.transform.localRotation = Quaternion.identity;
            go.transform.localScale = new Vector3(size, size, 1f);

            var filter = go.AddComponent<MeshFilter>();
            filter.sharedMesh = BuildQuadMesh($"PowerUp_GlowMesh_{spriteName}");

            var renderer = go.AddComponent<MeshRenderer>();
            renderer.sharedMaterial = mat;
            // Additive glow must depth-write OFF so it never occludes the mesh or
            // anything between the halo and the camera; shadow casting and probes
            // are pure noise on a transparent additive quad.
            renderer.shadowCastingMode = UnityEngine.Rendering.ShadowCastingMode.Off;
            renderer.receiveShadows = false;
            renderer.lightProbeUsage = UnityEngine.Rendering.LightProbeUsage.Off;
            renderer.reflectionProbeUsage = UnityEngine.Rendering.ReflectionProbeUsage.Off;

            // Billboard component: makes the quad face the camera every frame.
            // Full free-rotation billboard (lockYAxis=false) gives the true
            // Subway-Surfers "always a sphere" read.
            var billboard = go.AddComponent<PowerUps.Billboard>();
            billboard.lockYAxis = false;

            return go;
        }

        /// <summary>
        /// Builds (and stores on the prefab asset via AddObjectToAsset in <see cref="Save"/>)
        /// a unit quad centred on the origin and facing +Z. Used by <see cref="AddGlowHalo"/>
        /// as the halo geometry — a literal 1×1 plane, the halo rotation + scale moulds it.
        /// </summary>
        private static Mesh BuildQuadMesh(string name)
        {
            var mesh = new Mesh { name = name };
            mesh.vertices = new Vector3[]
            {
                new Vector3(-0.5f, -0.5f, 0f),
                new Vector3( 0.5f, -0.5f, 0f),
                new Vector3( 0.5f,  0.5f, 0f),
                new Vector3(-0.5f,  0.5f, 0f),
            };
            mesh.uv = new Vector2[]
            {
                new Vector2(0f, 0f),
                new Vector2(1f, 0f),
                new Vector2(1f, 1f),
                new Vector2(0f, 1f),
            };
            mesh.triangles = new int[] { 0, 2, 1, 0, 3, 2 };
            mesh.RecalculateNormals();
            return mesh;
        }


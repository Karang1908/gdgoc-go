        private static bool Exists(string path) => AssetDatabase.LoadAssetAtPath<GameObject>(path) != null;

        private static GameObject NewRoot(string name) => new GameObject(name);

        /// <summary>
        /// Adds a kinematic Rigidbody to anything that both has a collider and moves.
        ///
        /// Every streamed object is repositioned every frame. A collider with no
        /// Rigidbody is a <i>static</i> collider, and moving one makes PhysX rebuild its
        /// static broadphase — with a few hundred coins and obstacles in flight that is a
        /// per-frame cost the WebGL build cannot absorb. A kinematic Rigidbody moves them
        /// into the dynamic broadphase, which is what it is designed for, and still sends
        /// trigger messages against the player's kinematic trigger collider.
        /// </summary>
        /// <summary>
        /// Sizes a trigger to the renderer bounds of the mesh under it, in the root's
        /// local space, so the hitbox matches what the player sees.
        ///
        /// Falls back to <paramref name="fallback"/> when the mesh has no renderers,
        /// rather than leaving a zero-size collider that nothing can ever hit.
        ///
        /// The bounds are shrunk slightly on X/Z: renderer bounds are an axis-aligned box
        /// around the whole mesh, so for anything round or angled the corners enclose a
        /// lot of empty air. Trimming keeps a near-miss feeling like a near-miss instead
        /// of a phantom collision.
        /// </summary>
        private static void FitTriggerToMesh(BoxCollider collider, GameObject mesh, Vector3 fallback)
        {
            if (collider == null) return;

            var renderers = mesh != null ? mesh.GetComponentsInChildren<Renderer>(true) : null;
            if (renderers == null || renderers.Length == 0)
            {
                collider.size = fallback;
                collider.center = new Vector3(0f, fallback.y * 0.5f, 0f);
                return;
            }

            Bounds bounds = renderers[0].bounds;
            for (int i = 1; i < renderers.Length; i++) bounds.Encapsulate(renderers[i].bounds);

            // Renderer.bounds is world space; the prefab root sits at the origin while
            // being built, so world == local here.
            Vector3 size = bounds.size;
            Vector3 centre = bounds.center;

            const float lateralTrim = 0.82f;
            size.x = Mathf.Max(0.2f, size.x * lateralTrim);
            size.z = Mathf.Max(0.2f, size.z * lateralTrim);
            size.y = Mathf.Max(0.2f, size.y);

            collider.size = size;
            collider.center = centre;
        }

        private static void MakeMovingTrigger(GameObject root)
        {
            var body = root.GetComponent<Rigidbody>();
            if (body == null) body = root.AddComponent<Rigidbody>();
            body.isKinematic = true;
            body.useGravity = false;
            // Nothing here is simulated, so skip the interpolation and sleep bookkeeping.
            body.interpolation = RigidbodyInterpolation.None;
            body.collisionDetectionMode = CollisionDetectionMode.Discrete;
        }

        /// <summary>
        /// Instantiates an imported FBX as a child named "Mesh". Returns null (with a
        /// warning) when the model is missing, so one absent file cannot abort the batch.
        /// </summary>
        /// <summary>
        /// Shifts a mesh child down so the TOP of its bounds sits on y = 0.
        ///
        /// Used only by the road: it is the surface everything else stands on, so the
        /// plane the player drives at has to be y = 0. Props use the opposite alignment
        /// (bottom on the ground) which <see cref="AttachMesh"/> applies by default.
        /// </summary>
        private static void AlignTopSurfaceToGround(GameObject mesh)
        {
            if (mesh == null) return;

            var renderers = mesh.GetComponentsInChildren<Renderer>(true);
            if (renderers.Length == 0) return;

            Bounds b = renderers[0].bounds;
            for (int i = 1; i < renderers.Length; i++) b.Encapsulate(renderers[i].bounds);

            Vector3 p = mesh.transform.localPosition;
            p.y -= b.max.y;
            mesh.transform.localPosition = p;
        }

        private static GameObject AttachMesh(GameObject root, string fbxPath, float scale,
                                             bool upright = false, Quaternion? rotation = null)
        {
            var model = AssetDatabase.LoadAssetAtPath<GameObject>(fbxPath);
            if (model == null)
            {
                Debug.LogWarning($"[PrefabsBuilder] Missing model: {fbxPath} — skipping {root.name}.");
                return null;
            }

            var instance = (GameObject)PrefabUtility.InstantiatePrefab(model);
            if (instance == null)
            {
                Debug.LogWarning($"[PrefabsBuilder] Could not instantiate {fbxPath}.");
                return null;
            }

            instance.name = "Mesh";
            instance.transform.SetParent(root.transform, false);
            instance.transform.localPosition = Vector3.zero;
            // Z-up sources are stood up here rather than at each call site, and only ever
            // on the mesh child so the root's collider stays axis-aligned.
            instance.transform.localRotation = rotation ?? (upright ? QuaterniusUprightRotation : Quaternion.identity);
            instance.transform.localScale = Vector3.one * scale;

            // The mesh child may be rotated (Z-up sources) or have a centred
            // pivot (some Kenney props authored around the origin rather than
            // at the ground), so its own bounds can be offset from the root
            // after parenting. If the lowest point now sits below y = 0,
            // drop it so the object does not render half-buried under the
            // scene. This only fires when actually needed — props authored
            // with their base at the origin already have min.y = 0 and are
            // left untouched (preserves the existing player-car / cone / etc.
            // alignment behaviour from pre-power-up-import).
            {
                var renderers = instance.GetComponentsInChildren<Renderer>(true);
                if (renderers.Length > 0)
                {
                    Bounds b = renderers[0].bounds;
                    for (int i = 1; i < renderers.Length; i++) b.Encapsulate(renderers[i].bounds);
                    if (b.min.y < -0.0001f)
                        instance.transform.localPosition = new Vector3(0f, -b.min.y, 0f);
                }
            }
            return instance;
        }

        /// <summary>
        /// Assigns a tag, warning instead of throwing if it is not registered.
        /// <c>ProjectSetup.EnsureTags</c> is called first so this should never fire — the
        /// guard exists because an unregistered tag previously threw and killed the batch.
        /// </summary>
        private static void SafeSetTag(GameObject go, string tag)
        {
            try
            {
                go.tag = tag;
            }
            catch (UnityException)
            {
                Debug.LogWarning($"[PrefabsBuilder] Tag \"{tag}\" is not registered. " +
                                 "Run \"GDG Go > 1. Project Setup\", or add it under " +
                                 "Edit > Project Settings > Tags and Layers.");
            }
        }

        private static bool Save(GameObject root, string path)
        {
            // Meshes generated in code (the road surface and lane markings) live only in
            // memory, so the saved prefab would reference assets that were never written
            // and load with nothing to draw.
            //
            // AddObjectToAsset AFTER SaveAsPrefabAsset does not work: the prefab has
            // already serialised its MeshFilter references by then, so the meshes end up
            // stored in the file while every filter still points at nothing. Verified —
            // the asset held all 13 meshes and every renderer measured zero size.
            //
            // The fix is to write the meshes as their own asset FIRST, so they have a real
            // asset path before the prefab is serialised and the references resolve.
            var generated = new List<Mesh>();
            foreach (var filter in root.GetComponentsInChildren<MeshFilter>(true))
            {
                Mesh mesh = filter.sharedMesh;
                if (mesh == null) continue;
                if (!string.IsNullOrEmpty(AssetDatabase.GetAssetPath(mesh))) continue;   // already an asset
                generated.Add(mesh);
            }

            if (generated.Count > 0)
            {
                string meshPath = Path.ChangeExtension(path, null) + "_Meshes.asset";
                AssetDatabase.CreateAsset(generated[0], meshPath);
                for (int i = 1; i < generated.Count; i++)
                    AssetDatabase.AddObjectToAsset(generated[i], generated[0]);
                AssetDatabase.SaveAssets();
            }

            PrefabUtility.SaveAsPrefabAsset(root, path);
            Object.DestroyImmediate(root);
            Debug.Log($"[PrefabsBuilder] Built {path}");
            return true;
        }

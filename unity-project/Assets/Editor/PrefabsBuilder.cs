            built += BuildScenery("Prop_Tree", $"{Quaternius}/SimpleNature/Tree1.fbx", MaterialLibrary.Foliage(), scale: TreeScale, upright: true) ? 1 : 0;
            built += BuildScenery("Prop_Bush", $"{Quaternius}/SimpleNature/Bush1.fbx", MaterialLibrary.Foliage(), scale: BushScale, upright: true) ? 1 : 0;
        }


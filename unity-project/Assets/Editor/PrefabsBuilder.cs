        public static readonly (string Name, string Fbx)[] PedestrianModels =
        {
            ("Ped_Male_Casual",      "AnimatedMen/Male_Casual.fbx"),
            ("Ped_Male_Shirt",       "AnimatedMen/Male_Shirt.fbx"),
            ("Ped_Male_Suit",        "AnimatedMen/Male_Suit.fbx"),
            ("Ped_Male_LongSleeve",  "AnimatedMen/Male_LongSleeve.fbx"),
            ("Ped_Female_Casual",    "AnimatedWomen/Female_Casual.fbx"),
            ("Ped_Female_Dress",     "AnimatedWomen/Female_Dress.fbx"),
            ("Ped_Female_TankTop",   "AnimatedWomen/Female_TankTop.fbx"),
            ("Ped_Female_Alt",       "AnimatedWomen/Female_Alternative.fbx"),
        };

        /// <summary>
        /// The character packs are the exception to the Quaternius x100 rule: they are
        /// authored at metre scale already. Measured in the editor, <c>Male_Casual</c>
        /// imports at <b>1.96 x 4.93 x 1.13</b> and is already upright, so 1.8/4.93
        /// gives a ~1.8 m pedestrian. <see cref="ModelAxisFixer"/> exempts these folders
        /// from the prop import scale for the same reason.
        /// </summary>
        private const float PedestrianScale = 0.36518f;

        private static void BuildPedestrianBatch(ref int built)
        {
            MaterialLibrary.EnsureFolder($"{Root}/Pedestrians");
            foreach (var (name, fbx) in PedestrianModels)
                built += BuildPedestrian(name, $"{Quaternius}/{fbx}") ? 1 : 0;
        }

        /// <summary>
        /// Builds (or returns the existing) AnimatorController for a given character FBX,
        /// with a single "Walk" state looping this FBX's own embedded <c>Man_Walk</c> /
        /// <c>Female_Walk</c> clip.
        ///
        /// One controller per FBX rather than one shared controller because the character
        /// packs are imported as <b>Generic</b> rigs (see <see cref="ModelAxisFixer"/>) and
        /// Generic clips are bound to their source rig's Avatar — playing <c>Man_Walk</c>
        /// on a <c>Female_CasualAvatar</c> would not retarget the way a Humanoid clip
        /// would, since the bone hierarchies are technically separate even if structurally
        /// similar. To stay correct under Generic, every FBX gets its own controller that
        /// references its own walk clip, paired with the FBX's own Avatar on the Animator.
        ///
        /// Walk clip lookup by name suffix: the Quaternius character pack names its clips
        /// <c>HumanArmature|Man_Walk</c> for the AnimatedMen folder and
        /// <c>HumanArmature|Female_Walk</c> for the AnimatedWomen folder, so we look for
        /// any clip whose name ends in <c>|Man_Walk</c> or <c>|Female_Walk</c> regardless
        /// of the package name preceding the bar. Any preview<nbsp>clip (<c>__preview__</c>)
        /// is excluded.
        ///
        /// Idempotent: the controller is a saved asset, so re-running setup leaves it
        /// alone (the existence check skips the build).
        /// </summary>
        private static RuntimeAnimatorController EnsureWalkController(string fbxPath)
        {
            string leafName = Path.GetFileNameWithoutExtension(fbxPath);
            string controllerPath = $"Assets/Animations/PedestrianWalk_{leafName}.controller";

            var existing = AssetDatabase.LoadAssetAtPath<RuntimeAnimatorController>(controllerPath);
            if (existing != null) return existing;

            MaterialLibrary.EnsureFolder("Assets/Animations");

            AnimationClip walkClip = null;
            foreach (var sub in AssetDatabase.LoadAllAssetsAtPath(fbxPath))
            {
                if (!(sub is AnimationClip c)) continue;
                if (c.name.StartsWith("__preview__")) continue;
                if (c.name.EndsWith("|Man_Walk") || c.name.EndsWith("|Female_Walk"))
                {
                    walkClip = c;
                    break;
                }
            }
            if (walkClip == null)
            {
                Debug.LogWarning($"[PrefabsBuilder] Walk clip not found inside {fbxPath} — " +
                                 "pedestrian will spawn idle. Run GDG Go > 5c. Clear Quaternius Axis Bake first.");
                return null;
            }

            AnimatorController controller = AnimatorController.CreateAnimatorControllerAtPath(controllerPath);
            if (controller == null) return null;

            var rootStateMachine = controller.layers.Length > 0 ? controller.layers[0].stateMachine : null;
            if (rootStateMachine == null) return null;

            var walkState = rootStateMachine.AddState("Walk");
            walkState.motion = walkClip;
            rootStateMachine.defaultState = walkState;

            EditorUtility.SetDirty(controller);
            AssetDatabase.SaveAssets();
            Debug.Log($"[PrefabsBuilder] Built {leafName} walk controller using {walkClip.name}.");
            return controller;
        }

        /// <summary>
        /// Loads the Avatar sub-asset that Unity auto-generates for a Humanoid FBX import,
        /// so the prefab's Animator can be bound to the correct rig. Each character FBX's
        /// avatar carries its own retargeting mapping — even within the Quaternius pack
        /// (male vs female), so we look it up per FBX rather than sharing.
        /// </summary>
        private static Avatar LoadAvatarFor(string fbxPath)
        {
            foreach (var sub in AssetDatabase.LoadAllAssetsAtPath(fbxPath))
            {
                if (sub is Avatar av && !string.IsNullOrEmpty(av.name)) return av;
            }
            return null;
        }

        private static bool BuildPedestrian(string name, string fbxPath)
        {
            string path = $"{Root}/Pedestrians/{name}.prefab";
            if (Exists(path)) return false;

            GameObject root = NewRoot(name);
            GameObject mesh = AttachMesh(root, fbxPath, scale: PedestrianScale);
            if (mesh == null) { Object.DestroyImmediate(root); return false; }

            // These meshes name their slots after the body part, so each pedestrian can
            // be dressed properly instead of being one flat colour.
            MaterialLibrary.AssignNamedPalette(mesh,
                new System.Collections.Generic.Dictionary<string, Material>
                {
                    { "Skin",  MaterialLibrary.Skin() },
                    { "Hair",  MaterialLibrary.GetOrCreate($"{MaterialLibrary.WorldFolder}/Hair.mat", new Color(0.16f, 0.12f, 0.10f), 0.2f, 0f) },
                    { "Eyes",  MaterialLibrary.GetOrCreate($"{MaterialLibrary.WorldFolder}/Eyes.mat", new Color(0.10f, 0.10f, 0.12f), 0.6f, 0f) },
                    { "Shirt", MaterialLibrary.Clothing() },
                    { "Pants", MaterialLibrary.GetOrCreate($"{MaterialLibrary.WorldFolder}/Pants.mat", new Color(0.22f, 0.24f, 0.32f), 0.05f, 0f) },
                    { "Shoes", MaterialLibrary.GetOrCreate($"{MaterialLibrary.WorldFolder}/Shoes.mat", new Color(0.12f, 0.11f, 0.10f), 0.3f, 0f) },
                    { "Socks", MaterialLibrary.GetOrCreate($"{MaterialLibrary.WorldFolder}/Socks.mat", new Color(0.80f, 0.80f, 0.78f), 0.05f, 0f) },
                },
                fallback: MaterialLibrary.Clothing());

            // PedestrianNPC.OnTriggerEnter charges Heat when the player mounts the kerb,
            // so it needs a trigger to receive that message at all. Sized to a person
            // rather than fitted to the mesh: the T-pose these characters ship in has the
            // arms out wide, and a bounds-fitted box would be about as wide as it is tall.
            var collider = root.AddComponent<CapsuleCollider>();
            collider.isTrigger = true;
            collider.height = 1.8f;
            collider.radius = 0.3f;
            collider.center = new Vector3(0f, 0.9f, 0f);

            root.AddComponent<Pedestrians.PedestrianNPC>();

            // Drive the walk cycle. The Quaternius character FBX importer has been
            // configured (by ModelAxisFixer) to a Generic rig with an auto-generated
            // Generic Avatar, and a per-FBX PedestrianWalk controller plays this FBX's
            // own embedded Man_Walk / Female_Walk clip. Without an Animator, the
            // pedestrian spawned in T-pose and slid along Z — set the controller here
            // so they walk from spawn.
            var animator = root.AddComponent<Animator>();
            animator.applyRootMotion = false;
            animator.cullingMode = AnimatorCullingMode.AlwaysAnimate;
            animator.avatar = LoadAvatarFor(fbxPath);
            // The NPC field is what PedestrianNPC.SetWalking hooks to; route it now so
            // runtime doesn't have to look it up.
            var npc = root.GetComponent<Pedestrians.PedestrianNPC>();
            if (npc != null) npc.animator = animator;
            var controller = EnsureWalkController(fbxPath);
            if (controller != null) animator.runtimeAnimatorController = controller;

            // Streamed and moving, so it needs a kinematic body like every other
            // streamed collider — see MakeMovingTrigger.
            MakeMovingTrigger(root);

            return Save(root, path);
        }

        private static bool BuildScenery(string name, string fbxPath, Material palette = null, float scale = 1f, bool upright = false)
        {
            string path = $"{Root}/Scenery/{name}.prefab";
            if (Exists(path)) return false;

            GameObject root = NewRoot(name);
            GameObject mesh = AttachMesh(root, fbxPath, scale, upright);
            if (mesh == null) { Object.DestroyImmediate(root); return false; }

            if (palette != null) MaterialLibrary.AssignPalette(mesh, palette);

            // Scenery never has colliders — it exists only to sell speed.
            return Save(root, path);
        }


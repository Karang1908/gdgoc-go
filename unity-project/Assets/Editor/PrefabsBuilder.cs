        // Generated power-up meshes — REMOVED (were proc-gen).
        //
        // The previous proc-gen meshes (horseshoe / X-cross / hex shield / bolt /
        // snowflake) read as flat low-poly shapes at game speed and were retired in
        // favour of real Quaternius RPG Assets (Heart, Star, Armor_Metal,
        // Arrow_Golden, Snowflake3 + Potion6_Filled for fuel). They ship as FBX under
        // Assets/Models/Quaternius/RPG/ and are wired in BuildPowerUps /
        // BuildFuelPrefab below. The mesh-builder block that lived here was deleted
        // in this pass — the slab/box helpers (AddSlab/AddSlabAlong/AddBoxTris) were
        // only used by those generators and were removed with them.
        // ==================================================================

        /// <summary>
        /// Builds the lane markings at the lane boundaries, plus solid edge lines at the
        /// outside of the drivable surface.
        ///
        /// The source mesh only carries a single marking down its centre, which on a
        /// 3-lane road sits in the middle of the centre lane — so the road reads as one
        /// wide strip with a stripe through it rather than as three lanes. The dividers
        /// belong at the lane BOUNDARIES (x = +-1.5 for LaneModel.LaneWidth = 3), and the
        /// dashes have to be built here because no mesh in the pack has them.
        ///
        /// Quads rather than cubes: a lane marking is painted onto the road, it has no
        /// thickness, and a quad is 2 triangles against a cube's 12.
        /// </summary>
        private static void BuildLaneMarkings(GameObject root)
        {
            Material paint = MaterialLibrary.RoadLine();

            // Lane boundaries: between lane 0/1 and lane 1/2.
            float halfLane = Gameplay.LaneModel.LaneWidth * 0.5f;
            BuildDashedLine(root, -halfLane, paint);
            BuildDashedLine(root, +halfLane, paint);

            // Solid lines at the outer edge of the drivable area.
            float edge = Gameplay.LaneModel.LaneWidth * 1.5f;
            BuildSolidLine(root, -edge, paint);
            BuildSolidLine(root, +edge, paint);
        }

        private const float MarkingWidth = 0.16f;
        private const float MarkingLift = 0.012f;   // clear of the road to beat z-fighting
        private const float DashLength = 2.2f;
        private const float DashGap = 1.8f;

        private static void BuildDashedLine(GameObject root, float x, Material paint)
        {
            float tile = RoadTileWidth;
            float stride = DashLength + DashGap;
            int count = Mathf.Max(1, Mathf.RoundToInt(tile / stride));
            // Recompute the stride from the rounded count so dashes meet seamlessly across
            // the tile join instead of drifting out of phase every tile.
            stride = tile / count;

            for (int i = 0; i < count; i++)
            {
                float z = -tile * 0.5f + stride * (i + 0.5f);
                MakeMarkingQuad(root, $"Dash_{x:0.0}_{i}", new Vector3(x, MarkingLift, z),
                                new Vector2(MarkingWidth, DashLength), paint);
            }
        }

        private static void BuildSolidLine(GameObject root, float x, Material paint)
        {
            MakeMarkingQuad(root, $"EdgeLine_{x:0.0}", new Vector3(x, MarkingLift, 0f),
                            new Vector2(MarkingWidth, RoadTileWidth), paint);
        }

        /// <summary>A flat, upward-facing quad of the given size, centred on <paramref name="position"/>.</summary>
        private static void MakeMarkingQuad(GameObject root, string name, Vector3 position, Vector2 size, Material paint)
        {
            MakeQuad(root, name, position, size, paint);
        }

        private static void BuildSceneryBatch(ref int built)
        {
            // Front-row skyline — the dense, varied mid-height wall that sells speed.
            // Measured (in pack units, before buildingScale): standard commercial a..n span

    /// <summary>
    /// Builds every prefab the game needs from the imported packs.
    ///
    /// Art sourcing is deliberate and evidence-based:
    ///   * <b>Vehicles, cones, buildings — Kenney.</b> Those FBX reference a
    ///     <c>colormap.png</c> that ships in the same folder, so they import textured.
    ///   * <b>Road, coin, signs — Quaternius.</b> Those packs contain no textures and no
    ///     vertex colours at all (checked against the source zips), so their meshes get
    ///     flat materials from <see cref="MaterialLibrary"/>. That is how those packs are
    ///     designed to be used — the colour lives in the material, not the mesh.
    ///
    /// Every prefab is built as: a plain root that owns the collider, physics and
    /// gameplay components, with the imported mesh parented underneath as a child named
    /// "Mesh". Keeping them separate means visual tweaks (rotating a car that faces the
    /// wrong way, nudging scale) never disturb the collider or the gameplay code.
    ///
    /// Idempotent: an existing prefab is left completely alone.
    /// </summary>
    public static class PrefabsBuilder
    {
        private const string Root = "Assets/Prefabs";
        private const string Kenney = "Assets/Models/Kenney";
        private const string Quaternius = "Assets/Models/Quaternius";

        /// <summary>
        /// Prefabs whose geometry comes from a Quaternius mesh, and which therefore bake
        /// in the source's orientation. <see cref="ModelAxisFixer"/> changes that
        /// orientation at import, but every Build* method skips a prefab that already
        /// exists — so without deleting these first, an axis fix would silently have no
        /// effect on the prefabs that most needed it.
        /// </summary>
        private static readonly string[] QuaterniusDerivedPrefabs =
        {
            $"{Root}/Road/Street_Straight.prefab",
            $"{Root}/Obstacles/Obstacle_StopSign.prefab",
            $"{Root}/Obstacles/Obstacle_TrafficLight.prefab",
            $"{Root}/Scenery/Prop_Streetlight.prefab",
            $"{Root}/Scenery/Prop_Tree.prefab",
            $"{Root}/Scenery/Prop_Bush.prefab",
            $"{Root}/Coin.prefab",
            // Legacy single power-up prefab (now superseded by per-type set).
            $"{Root}/PowerUp.prefab",
            $"{Root}/PowerUps/PowerUp_Magnet.prefab",
            $"{Root}/PowerUps/PowerUp_TwoX.prefab",
            $"{Root}/PowerUps/PowerUp_Shield.prefab",
            $"{Root}/PowerUps/PowerUp_Nitro.prefab",
            $"{Root}/PowerUps/PowerUp_Freeze.prefab",
            // Fuel: distinct RPG bottle prefab (was a Coin reuse).
            $"{Root}/PowerUps/Fuel.prefab",
        };

        /// <summary>
        /// Deletes the prefabs built from Quaternius meshes so the next BuildAll rebuilds
        /// them against the corrected axes. Safe to run at any time — everything it
        /// removes is regenerated by <see cref="BuildAll"/>.
        /// </summary>
        [MenuItem("GDG Go/2b. Rebuild Quaternius Prefabs", priority = 11)]
        public static void RebuildQuaterniusPrefabs()
        {
            DeleteQuaterniusDerivedPrefabs();
            BuildAll();
            SceneBuilder.BuildGameScene();   // scene holds direct references to them
        }

        /// <summary>
        /// Removes the Quaternius-derived prefabs so the next <see cref="BuildAll"/>
        /// regenerates them. Everything deleted here is rebuilt from source meshes.
        /// </summary>
        public static void DeleteQuaterniusDerivedPrefabs()
        {
            int deleted = 0;
            foreach (string path in QuaterniusDerivedPrefabs)
            {
                // Procedural meshes are written to a sibling "_Meshes.asset"; leaving it
                // behind would let a rebuilt prefab bind to the previous run's geometry.
                string meshPath = Path.ChangeExtension(path, null) + "_Meshes.asset";
                if (AssetDatabase.LoadMainAssetAtPath(meshPath) != null) AssetDatabase.DeleteAsset(meshPath);

                if (AssetDatabase.LoadAssetAtPath<GameObject>(path) == null) continue;
                if (AssetDatabase.DeleteAsset(path)) deleted++;
            }

            // Pedestrians too — same packs, same 100x scale.
            foreach (var (name, _) in PedestrianModels)
            {
                string path = $"{Root}/Pedestrians/{name}.prefab";
                if (AssetDatabase.LoadAssetAtPath<GameObject>(path) == null) continue;
                if (AssetDatabase.DeleteAsset(path)) deleted++;
            }

            // Old flat-disc glow materials (single _Glow.mat per pickup) and the new
            // two-layer _GlowCore/_GlowHalo variants. GetOrCreate returns existing
            // assets untouched, so leaving old additive-but-untextured glow mats in
            // place means the rebuilt prefabs would catch the old material and never
            // pick up the new radial-gradient textured ones. Deleting here forces
            // fresh creation on the next BuildAll().
            foreach (var (_, name, _, _, _, _, _) in PowerUpVariants)
            {
                DeleteGlowMaterials(name);
            }
            DeleteGlowMaterials("Fuel");

            AssetDatabase.Refresh();
            Debug.Log($"[PrefabsBuilder] Deleted {deleted} Quaternius-derived prefabs for rebuild.");
        }

        /// <summary>
        /// Deletes the old single "_Glow.mat" (flat horizontal-disc halo from the
        /// previous build) and the new "_GlowCore.mat" / "_GlowHalo.mat" pair so the
        /// next rebuild regenerates them from current code. Safe to call when none
        /// exist — DeleteAsset returns false for missing paths.
        /// </summary>
        private static void DeleteGlowMaterials(string name)
        {
            string[] candidates =
            {
                $"{MaterialLibrary.WorldFolder}/PowerUp_{name}_Glow.mat",
                $"{MaterialLibrary.WorldFolder}/PowerUp_{name}_GlowCore.mat",
                $"{MaterialLibrary.WorldFolder}/PowerUp_{name}_GlowHalo.mat",
                // Secondary painted-detail materials used by the new procedural
                // two-material icons (magnet red poles, shield white stripe,
                // secondary fallback). GetOrCreate returns the existing asset
                // untouched so a delete here is what forces the next BuildAll()
                // to regenerate them.
                $"{MaterialLibrary.WorldFolder}/PowerUp_{name}_Pole.mat",
                $"{MaterialLibrary.WorldFolder}/PowerUp_{name}_Stripe.mat",
                $"{MaterialLibrary.WorldFolder}/PowerUp_{name}_Secondary.mat",
            };
            foreach (string path in candidates)
            {
                if (AssetDatabase.LoadAssetAtPath<Material>(path) != null)
                    AssetDatabase.DeleteAsset(path);
            }
        }

        [MenuItem("GDG Go/2. Build All Prefabs", priority = 10)]
        public static void BuildAll()
        {
            // Tags must exist before any prefab tries to use them.
            ProjectSetup.EnsureTags();

            MaterialLibrary.EnsureFolder(Root);
            MaterialLibrary.EnsureFolder($"{Root}/Traffic");
            MaterialLibrary.EnsureFolder($"{Root}/Obstacles");
            MaterialLibrary.EnsureFolder($"{Root}/Road");
            MaterialLibrary.EnsureFolder($"{Root}/Scenery");

            int built = 0;

            built += BuildCoin() ? 1 : 0;
            // Per-type power-ups: 5 prefabs (was 1). See PowerUpVariants.
            // Fuel: distinct RPG bottle prefab so it doesn't reuse the coin disc.
            MaterialLibrary.EnsureFolder($"{Root}/PowerUps");
            BuildPowerUps(ref built);
            built += BuildFuelPrefab() ? 1 : 0;
            built += BuildPlayer() ? 1 : 0;
            built += BuildPolice() ? 1 : 0;

            // --- Traffic: Kenney vehicles, all textured. Speeds differ by class so
            //     overtaking a bus feels different from overtaking a hatchback. ---
            built += BuildTraffic("Traffic_Sedan", $"{Kenney}/CarKit/sedan.fbx") ? 1 : 0;
            built += BuildTraffic("Traffic_SUV", $"{Kenney}/CarKit/suv.fbx") ? 1 : 0;
            built += BuildTraffic("Traffic_Taxi", $"{Kenney}/CarKit/taxi.fbx") ? 1 : 0;
            built += BuildTraffic("Traffic_Van", $"{Kenney}/CarKit/van.fbx") ? 1 : 0;
            built += BuildTraffic("Traffic_Truck", $"{Kenney}/CarKit/truck.fbx") ? 1 : 0;
            built += BuildTraffic("Traffic_Delivery", $"{Kenney}/CarKit/delivery.fbx") ? 1 : 0;
            built += BuildTraffic("Traffic_Ambulance", $"{Kenney}/CarKit/ambulance.fbx") ? 1 : 0;
            built += BuildTraffic("Traffic_Firetruck", $"{Kenney}/CarKit/firetruck.fbx") ? 1 : 0;

            // --- Obstacles. Low ones can be jumped; tall ones must be dodged. ---
            built += BuildObstacle("Obstacle_Cone", $"{Kenney}/CarKit/cone.fbx", jumpable: true) ? 1 : 0;
            built += BuildObstacle("Obstacle_Tire", $"{Kenney}/CarKit/debris-tire.fbx", jumpable: true) ? 1 : 0;
            built += BuildObstacle("Obstacle_Door", $"{Kenney}/CarKit/debris-door.fbx", jumpable: true) ? 1 : 0;
            built += BuildObstacle("Obstacle_Box", $"{Kenney}/CarKit/box.fbx", jumpable: true) ? 1 : 0;
            // Quaternius props import at 100x (see the scale constants above), so these
            // are small numbers rather than large ones: a stop sign delivered 53.8 units
            // tall needs 0.0558 to reach a roadside 3 units.
            built += BuildObstacle("Obstacle_StopSign", $"{Quaternius}/ModularStreets/Sign_Stop.fbx", jumpable: false, MaterialLibrary.Metal(), scale: StopSignScale, upright: true) ? 1 : 0;
            built += BuildObstacle("Obstacle_TrafficLight", $"{Quaternius}/ModularStreets/TrafficLight.fbx", jumpable: false, MaterialLibrary.Metal(), scale: TrafficLightScale, upright: true) ? 1 : 0;

            // --- Road tiles. Quaternius, so they need a palette. ---
            built += BuildRoadTile("Street_Straight", $"{Quaternius}/ModularStreets/Street_Straight.fbx") ? 1 : 0;

            // --- Scenery. Kenney city kits, textured. ---
            BuildSceneryBatch(ref built);

            // --- Pedestrians. Quaternius character packs. ---
            BuildPedestrianBatch(ref built);

            AssetDatabase.SaveAssets();
            AssetDatabase.Refresh();
            Debug.Log($"[PrefabsBuilder] Done — {built} prefab(s) created (existing ones left untouched).");
        }


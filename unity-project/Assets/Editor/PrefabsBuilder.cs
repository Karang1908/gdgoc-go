            foreach (string id in industrial)
                built += BuildScenery($"Scenery_ind-{id}", $"{Kenney}/CityKitIndustrial/{id}.fbx") ? 1 : 0;

            // Industrial continues into o..t + chimneys + tank — heavier/blockier than
            // commercial, useful as a mid-back silhouette where the front row breaks.

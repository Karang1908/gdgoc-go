            // Low-detail towers: thin (~0.5 wide) and varied in height (0.7..2.0). Used as a
            // sparse *backfill* between the front row and the skyscrapers so the horizon isn't
            // a hard wall — three thin towers in the distance read as a neighbourhood beyond
            // the focal buildings without competing for the eye.
            string[] lowDetail = { "low-detail-building-a", "low-detail-building-b", "low-detail-building-c", "low-detail-building-d", "low-detail-building-e", "low-detail-building-f", "low-detail-building-g", "low-detail-building-h", "low-detail-building-i", "low-detail-building-j", "low-detail-building-k", "low-detail-building-l", "low-detail-building-m", "low-detail-building-n" };
            foreach (string id in lowDetail)
                built += BuildScenery($"Scenery_{id}", $"{Kenney}/CityKitCommercial/{id}.fbx") ? 1 : 0;

            // Industrial chimneys: tall thin verticals that puncture the skyline and add a
            // distinct silhouette vs the boxy commercial back row. The tank is a low, wide
            // form good for the verge between buildings.
            foreach (string id in new[] { "chimney-basic", "chimney-large", "chimney-medium", "chimney-small", "detail-tank" })
                built += BuildScenery($"Scenery_ind-{id}", $"{Kenney}/CityKitIndustrial/{id}.fbx") ? 1 : 0;


            foreach (string id in industrialFar)
                built += BuildScenery($"Scenery_ind-{id}", $"{Kenney}/CityKitIndustrial/{id}.fbx") ? 1 : 0;

            // Tall focal points for the back row. Measured: skyscrapers ~1.3 x 4.1 x 1.3,
